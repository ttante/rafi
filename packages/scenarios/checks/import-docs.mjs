// Generates checks/registry.ts from REWRITE_SCENARIOS.md (headings and Covers lines) and the Must-pass and Partial
// lists of REWRITE_ARCHITECTURE.md section 14 (plan choice C21; Partial since M5 10.10, for the gate's tiers).
// Rerun when the docs change:
//   node packages/scenarios/checks/import-docs.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const ID = /\b[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+\b/g;

export function scenariosFromDoc(text) {
  const lines = text.split("\n");
  const found = [];
  for (let i = 0; i < lines.length; i += 1) {
    const heading = /^#### (S-[A-Z]+-\d+) — (.+)$/.exec(lines[i]);
    if (!heading) continue;
    const coversLine = lines.slice(i + 1, i + 6).find((l) => l.startsWith("- **Covers:**")) ?? "";
    const covers = [...new Set(coversLine.replace("- **Covers:**", "").match(ID) ?? [])];
    found.push({ id: heading[1], title: heading[2].trim(), covers });
  }
  return found;
}

function listsFromArch(text, label) {
  const map = new Map();
  const section = text.slice(text.indexOf("## 14. Milestones"), text.indexOf("## 15. Decisions"));
  let milestone = null;
  for (const line of section.split("\n")) {
    const head = /^### (M\d+)\./.exec(line);
    if (head) milestone = head[1];
    if (milestone && line.startsWith(`- **${label}:**`)) {
      // A Partial line's parentheses say which steps; only the ids outside them are listed scenarios.
      for (const id of line.replace(/\([^)]*\)/g, "").match(/S-[A-Z]+-\d+/g) ?? []) {
        map.set(id, [...(map.get(id) ?? []), milestone]);
      }
    }
  }
  return map;
}

export function milestonesFromArch(text) {
  return new Map([...listsFromArch(text, "Must pass")].map(([id, ms]) => [id, ms[ms.length - 1]]));
}

export function buildRegistry(scnText, archText) {
  const milestones = milestonesFromArch(archText);
  const partials = listsFromArch(archText, "Partial");
  return scenariosFromDoc(scnText).map((s) => ({ ...s, milestone: milestones.get(s.id) ?? null,
    partial: [...new Set(partials.get(s.id) ?? [])] }));
}

function wrapIds(ids) {
  const lines = [];
  let current = "";
  for (const id of ids.map((x) => JSON.stringify(x))) {
    if (current && current.length + id.length + 2 > 108) { lines.push(current); current = ""; }
    current = current ? `${current}, ${id}` : id;
  }
  if (current) lines.push(current);
  return `[\n    ${lines.join(",\n    ")}]`;
}

function render(entries) {
  const head = (e) => `  { id: ${JSON.stringify(e.id)}, milestone: ${JSON.stringify(e.milestone)}, title: ` +
    JSON.stringify(e.title.length > 60 ? `${e.title.slice(0, 57)}...` : e.title);
  const partial = (e) => (e.partial.length ? `,\n    partial: ${JSON.stringify(e.partial).replaceAll(",", ", ")}` : "");
  const rows = entries.map((e) => `${head(e)}, covers: ${wrapIds(e.covers)}${partial(e)} },`);
  return [
    "// Generated by checks/import-docs.mjs from REWRITE_SCENARIOS.md and REWRITE_ARCHITECTURE.md section 14.",
    "// Don't edit by hand; rerun the script when the docs change. The ledger test checks it against the docs.",
    "export interface Registered {",
    "  readonly id: string;",
    "  readonly milestone: string | null;",
    "  /** The milestones whose ARCH 14 Partial list names this scenario (some of its steps active then). */",
    "  readonly partial?: readonly string[];",
    "  readonly title: string;",
    "  readonly covers: readonly string[];",
    "}",
    "",
    "export const registry: readonly Registered[] = Object.freeze([",
    ...rows,
    "]);",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const scn = readFileSync(path.join(repo, "REWRITE_SCENARIOS.md"), "utf8");
  const arch = readFileSync(path.join(repo, "REWRITE_ARCHITECTURE.md"), "utf8");
  const entries = buildRegistry(scn, arch);
  writeFileSync(path.join(here, "registry.ts"), render(entries));
  console.log(`wrote ${entries.length} scenarios`);
}
